function normalizeRenderObject(value = {}) {
  return value && typeof value === 'object' && !Array.isArray(value) ? value : {};
}

function normalizeRenderText(value = '') {
  if (value == null) return '';
  return typeof value === 'string' ? value.trim() : String(value).trim();
}

function pickFirstText(...values) {
  for (const value of values) {
    const text = normalizeRenderText(value);
    if (text) return text;
  }
  return '';
}

function buildFreshnessLabel(value = '') {
  const normalized = normalizeRenderText(value);
  if (!normalized) return '';
  if (normalized === 'live') return 'Live';
  if (normalized === 'live_canonical') return 'Live canonical';
  if (normalized === 'derived_current') return 'Derived current';
  if (normalized === 'stale') return 'Stale';
  if (normalized === 'missing') return 'Missing';
  if (normalized === 'non_executable') return 'Non-executable';
  return normalized;
}

function toneForClassification(classification = '') {
  const normalized = normalizeRenderText(classification);
  if (!normalized) return 'neutral';
  if (['live', 'live_canonical', 'projection', 'canonical'].includes(normalized)) return 'good';
  if (['derived_current', 'derived', 'fallback'].includes(normalized)) return 'warn';
  if (['stale', 'missing'].includes(normalized)) return 'bad';
  return 'neutral';
}

export function normalizeQAEvidenceProvenance(trace = null) {
  const source = normalizeRenderObject(trace);
  const sourcePath = pickFirstText(source.sourcePath, source.source_route, source.route, source.routePath);
  const sourceClass = pickFirstText(source.sourceClass, source.classification, source.kind);
  const freshnessClass = pickFirstText(source.freshnessClass, source.freshness);
  const observedAt = pickFirstText(source.observedAt, source.updatedAt, source.generatedAt, source.createdAt, source.lastUpdatedAt);
  const fallbackUsed = typeof source.fallbackUsed === 'boolean'
    ? source.fallbackUsed
    : (typeof source.usedFallback === 'boolean' ? source.usedFallback : null);
  const derivedFrom = pickFirstText(source.derivedFrom, source.sourceTrace?.sourcePath);
  const generatedBy = normalizeRenderObject(source.generatedBy);
  const generatedByLabel = pickFirstText(generatedBy.label, [generatedBy.system, generatedBy.module].filter(Boolean).join(' | '));
  const sourceLabel = pickFirstText(source.label, source.kind, source.projectionId, source.projection_id, sourcePath);
  const domain = pickFirstText(source.domain, source.domainName, source.domainKey, source.domain_id, source.sourceDomain, sourceClass);
  const projectionId = pickFirstText(source.projectionId, source.projection_id, source.routeId, source.route_id, source.kind, sourceLabel);
  const generatedAt = pickFirstText(source.generatedAt, source.updatedAt, source.observedAt, source.createdAt, source.lastUpdatedAt);
  const hasProvenance = Boolean(domain || projectionId || sourcePath || sourceClass || freshnessClass || observedAt || generatedByLabel || derivedFrom || fallbackUsed !== null);
  const classification = pickFirstText(source.classification, source.kind, sourceClass);
  const freshness = buildFreshnessLabel(freshnessClass);
  const chips = [];

  if (domain) chips.push({ label: 'Domain', value: domain, tone: 'neutral' });
  if (projectionId) chips.push({ label: 'Projection', value: projectionId, tone: 'neutral' });
  if (sourcePath) chips.push({ label: 'Source', value: sourcePath, tone: 'neutral' });
  if (classification) chips.push({ label: 'Class', value: classification, tone: toneForClassification(classification) });
  if (freshness) chips.push({ label: 'Freshness', value: freshness, tone: toneForClassification(freshnessClass || classification) });
  if (generatedAt) chips.push({ label: 'Generated', value: generatedAt, tone: 'neutral' });
  if (observedAt && observedAt !== generatedAt) chips.push({ label: 'Observed', value: observedAt, tone: 'neutral' });
  if (generatedByLabel) chips.push({ label: 'Generated by', value: generatedByLabel, tone: 'neutral' });
  if (derivedFrom) chips.push({ label: 'Derived from', value: derivedFrom, tone: 'neutral' });
  if (fallbackUsed !== null) chips.push({ label: 'Fallback', value: fallbackUsed ? 'yes' : 'no', tone: fallbackUsed ? 'warn' : 'good' });

  return {
    domain,
    projectionId,
    sourcePath,
    sourceLabel,
    classification,
    freshness,
    freshnessClass: freshnessClass || null,
    generatedAt,
    observedAt,
    fallbackUsed,
    generatedByLabel: generatedByLabel || null,
    derivedFrom: derivedFrom || null,
    chips,
    hasProvenance,
  };
}

export function buildQAEvidenceProvenancePresentation(trace = null, { fallbackLabel = '' } = {}) {
  const provenance = normalizeQAEvidenceProvenance(trace);
  const chips = provenance.chips.slice();
  return {
    ...provenance,
    chips,
    hasRenderableProvenance: provenance.hasProvenance && chips.length > 0,
    fallbackLabel: provenance.hasProvenance ? '' : normalizeRenderText(fallbackLabel, ''),
  };
}
