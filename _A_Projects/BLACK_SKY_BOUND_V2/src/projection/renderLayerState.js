export function addDecalStamp(renderLayers, stamp) {
  if (!renderLayers?.decals) return null;
  const decals = renderLayers.decals;
  const next = {
    kind: stamp.kind ?? 'generic_decal',
    x: stamp.x,
    y: stamp.y,
    radius: Math.max(0.01, stamp.radius ?? 0.25),
    colour: stamp.colour ?? 'rgba(40,30,24,0.24)',
    opacity: Math.max(0, Math.min(1, stamp.opacity ?? 1)),
    rimColour: stamp.rimColour ?? null,
    softness: Number.isFinite(stamp.softness) ? Math.max(0, Math.min(1, stamp.softness)) : null,
    visualMaterial: stamp.visualMaterial ?? null,
    poolShape: stamp.poolShape ?? null,
    createdAtRevision: decals.revision + 1
  };
  decals.stamps.push(next);
  trimDecalBudget(renderLayers);
  decals.revision += 1;
  decals.dirty = true;
  return next;
}

export function markDecalsClean(renderLayers) {
  if (renderLayers?.decals) renderLayers.decals.dirty = false;
}

