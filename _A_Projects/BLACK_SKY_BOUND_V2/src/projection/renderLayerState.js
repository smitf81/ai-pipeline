function trimDecalBudget(renderLayers) {
  const max = RENDER_BUDGETS.decalStamps.maxActive;
  const decals = renderLayers.decals;
  if (decals.stamps.length <= max) return;
  const dropCount = decals.stamps.length - max;
  decals.stamps.splice(0, dropCount);
  decals.dropped += dropCount;
  renderLayers.diagnostics.droppedDecalStamps += dropCount;
}
